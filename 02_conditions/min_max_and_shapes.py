"""Условия: максимум и минимум, вписанные фигуры, знак функции."""

# Задача 1. Максимальное и минимальное из двух чисел
a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))
if a > b:
    print("Максимальное значение:", a)
    print("Минимальное значение:", b)
else:
    print("Максимальное значение:", b)
    print("Минимальное значение:", a)

# Задача 2. Впишется ли круг в квадрат
square_side = float(input("Введите длину стороны квадрата: "))
radius = float(input("Введите радиус круга: "))
if radius <= square_side / 2:
    print("Круг впишется в квадрат")
else:
    print("Круг не впишется в квадрат")

# Задача 3. Знак функции y = x²
x = float(input("Введите x: "))
y = x ** 2
if y < 0:
    print("Значение функции y меньше 0")
else:
    print("Значение функции y не меньше 0")

# Задача 4. Впишется ли квадрат в круг (диагональ квадрата не больше диаметра)
square_side = float(input("Введите длину стороны квадрата: "))
radius = float(input("Введите радиус круга: "))
if square_side * 2 ** 0.5 <= 2 * radius:
    print("Квадрат впишется в круг")
else:
    print("Квадрат не впишется в круг")

# Задача 5. Максимум через встроенную функцию max()
first = float(input("Введите первое число: "))
second = float(input("Введите второе число: "))
print("Максимум:", max(first, second))
