"""Вычисления по геометрическим формулам: периметры, площади, объёмы."""

import math

# Задача 1. Значение функции y = 7x + 5
x = int(input("Введите число: "))
y = 7 * x + 5
print("Ответ: y =", y)

# Задача 2. Периметр квадрата
side = int(input("Введите сторону квадрата: "))
print("Периметр квадрата:", side * 4)

# Задача 3. Длина окружности
r = float(input("Введите радиус: "))
print("Длина окружности:", 2 * math.pi * r)

# Задача 4. Площадь круга
r = float(input("Введите радиус: "))
print("Площадь круга:", math.pi * r ** 2)

# Задача 5. Гипотенуза прямоугольного треугольника (теорема Пифагора)
a = float(input("Введите катет a: "))
b = float(input("Введите катет b: "))
print("Гипотенуза:", math.sqrt(a ** 2 + b ** 2))

# Задача 6. Периметр треугольника
a = float(input("Введите сторону a: "))
b = float(input("Введите сторону b: "))
c = float(input("Введите сторону c: "))
print("Периметр треугольника:", a + b + c)

# Задача 7. Периметр прямоугольника
a = float(input("Введите длину: "))
b = float(input("Введите ширину: "))
print("Периметр прямоугольника:", 2 * (a + b))

# Задача 8. Площадь кольца
outer_r = float(input("Введите внешний радиус кольца: "))
inner_r = float(input("Введите внутренний радиус кольца: "))
print("Площадь кольца:", math.pi * (outer_r ** 2 - inner_r ** 2))

# Задача 9. Площадь поверхности и объём куба
edge = float(input("Введите ребро куба: "))
print("Площадь поверхности куба:", 6 * edge ** 2)
print("Объём куба:", edge ** 3)

# Задача 10. Периметр равнобедренной трапеции
lateral = float(input("Введите боковую сторону: "))
base1 = float(input("Введите первое основание: "))
base2 = float(input("Введите второе основание: "))
print("Периметр трапеции:", 2 * lateral + base1 + base2)
