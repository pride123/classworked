"""Простые вычисления: плотность, арифметика, средние значения, параллелепипед."""

# Задача 1. Плотность тела
mass = float(input("Введите массу тела: "))
volume = float(input("Введите объём тела: "))
print("Плотность тела:", mass / volume)

# Задача 2. Арифметические операции над двумя числами
a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))
print("Сумма:", a + b)
print("Разность:", a - b)
print("Произведение:", a * b)
print("Частное:", a / b if b != 0 else "делить на ноль нельзя")

# Задача 3. Среднее арифметическое и среднее геометрическое
a = float(input("Введите положительное число 1: "))
b = float(input("Введите положительное число 2: "))
print("Среднее арифметическое:", (a + b) / 2)
print("Среднее геометрическое:", (a * b) ** 0.5)

# Задача 4. Плотность населения
population = int(input("Количество жителей: "))
area = float(input("Площадь государства, км²: "))
print("Плотность населения, чел/км²:", population / area)

# Задача 5. Площадь поверхности и объём прямоугольного параллелепипеда
a = float(input("Ребро a: "))
b = float(input("Ребро b: "))
c = float(input("Ребро c: "))
print("Площадь поверхности:", 2 * (a * b + b * c + a * c))
print("Объём:", a * b * c)
