# Задача 1. Квадраты и кубы элементов массива с проверкой ввода
try:
    n = int(input("Введите размерность одномерного массива: "))
    if n <= 0:
        raise ValueError("размерность массива должна быть положительным числом")

    arr = [i + 1 for i in range(n)]
    print("Исходный массив:", arr)
    print("Квадраты элементов:", [x ** 2 for x in arr])
    print("Кубы элементов:", [x ** 3 for x in arr])
except ValueError as error:
    print(f"Ошибка: {error}")


# Задача 2. Минимальное из трёх чисел
def find_minimum(a, b, c):
    return min(a, b, c)


num1 = int(input("Введите первое число: "))
num2 = int(input("Введите второе число: "))
num3 = int(input("Введите третье число: "))
print("Наименьшее число:", find_minimum(num1, num2, num3))

