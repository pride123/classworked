# Задача 5. Площадь треугольника по координатам вершин
x1, y1 = map(float, input("Координаты вершины A (x y): ").split())
x2, y2 = map(float, input("Координаты вершины B (x y): ").split())
x3, y3 = map(float, input("Координаты вершины C (x y): ").split())
area = abs((x1 * (y2 - y3) + x2 * (y3 - y1) + x3 * (y1 - y2)) / 2)
print("Площадь треугольника:", area)
